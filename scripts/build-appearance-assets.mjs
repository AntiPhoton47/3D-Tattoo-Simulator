import { readFileSync, writeFileSync } from 'node:fs';
import { basename, resolve } from 'node:path';

const root = process.argv[2];
if (!root) throw new Error('Usage: node scripts/build-appearance-assets.mjs <extracted asset-pack root>');

const sources = {
  shirt_male: 'shirts01/clothes/elvs_crude_t-shirt_male/crude_male_shirt.obj',
  shirt_female: 'shirts01/clothes/joepal_crude_t-shirt_female/crudefemaletshirt.obj',
  cap: 'hats01/clothes/jujube_newsboy_cap/newsboy_cap.obj',
  beard_full: 'bodyparts05/clothes/wdg_scruffy_beard/scruffy_beard.obj',
  moustache: 'bodyparts05/clothes/rehmanpolanski_moustache_viking/moustacheviking.obj'
};

function encode(array) {
  return Buffer.from(array.buffer, array.byteOffset, array.byteLength).toString('base64');
}

function parseOBJ(file) {
  const positions = [], triangles = [];
  for (const raw of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    if (line.startsWith('v ')) {
      const [x, y, z] = line.split(/\s+/).slice(1, 4).map(Number);
      positions.push(x * .4, y * .4, z * .4);
    } else if (line.startsWith('f ')) {
      const face = line.split(/\s+/).slice(1).map(item => Number(item.split('/')[0]) - 1);
      for (let i = 1; i + 1 < face.length; i++) triangles.push(face[0], face[i], face[i + 1]);
    }
  }
  const vertexArray = new Float32Array(positions), indexArray = positions.length / 3 > 65535 ? new Uint32Array(triangles) : new Uint16Array(triangles);
  return { vertices: positions.length / 3, triangles: triangles.length / 3, positionType: 'f32', indexType: indexArray instanceof Uint32Array ? 'u32' : 'u16', positions: encode(vertexArray), indices: encode(indexArray) };
}

const output = {};
for (const [id, relative] of Object.entries(sources)) output[id] = { source: basename(relative), ...parseOBJ(resolve(root, relative)) };
writeFileSync('appearance-assets.js', `/* Selected CC0 MakeHuman mesh assets. Generated by scripts/build-appearance-assets.mjs. */\nwindow.INK_ATLAS_APPEARANCE_ASSETS=${JSON.stringify(output)};\n`);
console.log(`Wrote ${Object.keys(output).length} appearance meshes to appearance-assets.js`);
